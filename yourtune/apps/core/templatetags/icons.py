@register.simple_tag
def icon(name, class_name="", width="18", height="18", **kwargs):
    """
    Вставка SVG иконки по имени.

    Использование:
        {% icon 'edit'|safe %}
        {% icon 'edit'|safe class_name='my-icon' width='24' height='24' %}

    Атрибуты:
        - name: имя иконки из словаря ICONS
        - class_name: CSS класс (опционально)
        - width: ширина иконки (по умолчанию 18)
        - height: высота иконки (по умолчанию 18)

    Цвет:
        Иконки используют currentColor, что означает:
        - color: var(--yt-text) для основного цвета
        - color: var(--yt-accent) для акцентного цвета
        - и т.д.
    """
    svg = ICONS.get(name, "")
    if not svg:
        return ""

    attrs = []
    if class_name:
        attrs.append(f'class="{class_name}"')
    if width:
        attrs.append(f'width="{width}"')
    if height:
        attrs.append(f'height="{height}"')

    if attrs:
        svg = svg.replace("<svg", f'<svg {" ".join(attrs)}', 1)

    return mark_safe(svg)  # ← Помечаем как безопасный HTML
